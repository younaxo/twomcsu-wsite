import { isPublicAddress } from './ip-guard';

describe('isPublicAddress (SSRF, ADR-0102)', () => {
  it.each([
    '127.0.0.1',
    '127.255.255.254',
    '0.0.0.0',
    '10.0.0.5',
    '172.16.0.1',
    '172.31.255.255',
    '192.168.1.1',
    '169.254.169.254',
    '100.64.0.1',
    '198.18.0.51',
    '224.0.0.1',
    '255.255.255.255',
    '192.0.2.10',
    '::1',
    '::',
    'fc00::1',
    'fd12:3456::1',
    'fe80::1',
    'fe80::1%eth0',
    'ff02::1',
    '::ffff:127.0.0.1',
    '::ffff:10.0.0.1',
    '::ffff:7f00:1',
    '64:ff9b::a00:1',
    '2001:db8::1',
    '2002:c0a8:101::1',
    'localhost',
    'not-an-ip',
    '999.1.1.1',
  ])('блокирует %s', (address) => {
    expect(isPublicAddress(address)).toBe(false);
  });

  it.each([
    '1.1.1.1',
    '8.8.8.8',
    '93.184.216.34',
    '172.32.0.1',
    '2606:4700:4700::1111',
    '::ffff:8.8.8.8',
  ])('пропускает публичный %s', (address) => {
    expect(isPublicAddress(address)).toBe(true);
  });
});
