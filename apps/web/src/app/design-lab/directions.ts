/// Три кандидата визуального направления twomc.su. Единственное общее
/// ограничение — фирменный оранжевый. Всё остальное (типографика,
/// плотность, композиция, поверхности, форма, движение, образность) —
/// намеренно разное, чтобы сравнение было честным.

export type DirectionId = 'ember' | 'daylight' | 'signal';

export interface DirectionSpec {
  id: DirectionId;
  name: string;
  tagline: string;
  /// Характер и настроение одним абзацем — то, что должен почувствовать игрок.
  character: string;
  /// Откуда берётся образность: что в мире Minecraft/сервера делает этот стиль «своим».
  source: string;
  typography: { display: string; body: string; mono: string; note: string };
  color: { orange: string; orangeHex: string; neutrals: string; usage: string };
  surfaces: string;
  shape: string;
  density: string;
  composition: string;
  motion: string;
  imagery: string;
  /// Что будет memorable — одна вещь, на которую потрачена смелость.
  signature: string;
  risks: string[];
  /// Поддерживает ли тёмную тему переключателем (ember — только тёмная).
  themes: ('light' | 'dark')[];
}

